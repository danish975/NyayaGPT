import { NextRequest, NextResponse } from "next/server";
import { enforceRateLimit } from "@/lib/rate-limit";
import { getSecret, hmacVerify } from "@/lib/crypto";
import { groqChat, GroqError } from "@/lib/groq";

const SIMPLIFY_PROMPT = `You are NyayaGPT in "Explain Simply" mode. Rewrite the following legal answer so a 15-year-old can understand it.

Rules:
- Use plain everyday language. Short sentences.
- Keep all [n] citation markers exactly where they appear.
- Do not add new facts that are not in the original answer.
- Reply in the same language as the original answer.`;

const MAX_ANSWER_CHARS = 8000;

export async function POST(request: NextRequest) {
  const limited = enforceRateLimit(request, {
    name: "simplify",
    perIp: 10,
    global: 150,
    windowMs: 60_000,
  });
  if (limited) return limited;

  try {
    const body = await request.json().catch(() => null);
    const answer = typeof body?.answer === "string" ? body.answer : "";
    const answerToken = typeof body?.answerToken === "string" ? body.answerToken : "";

    if (!answer) {
      return NextResponse.json(
        { error: "Answer text is required" },
        { status: 400 }
      );
    }
    if (answer.length > MAX_ANSWER_CHARS) {
      return NextResponse.json({ error: "Answer is too long." }, { status: 400 });
    }

    // Only simplify text that /api/chat produced and signed. This stops the
    // endpoint from being used as a general-purpose LLM proxy.
    const secret = getSecret();
    if (!secret) {
      return NextResponse.json(
        { error: "Explain Simply is not configured on this server." },
        { status: 503 }
      );
    }
    if (!answerToken || !(await hmacVerify(`answer:${answer}`, answerToken, secret))) {
      return NextResponse.json(
        { error: "Only answers generated by NyayaGPT can be simplified." },
        { status: 403 }
      );
    }

    const apiKey = process.env.GROQ_API_KEY;
    if (!apiKey) {
      // Fallback: basic simplification
      const simplified = answer
        .replace(/\b(notwithstanding|aforementioned|hereinafter|thereof|pursuant|inter alia)\b/gi, "")
        .replace(/\s{2,}/g, " ")
        .trim();
      return NextResponse.json({
        simplified: `Here's the simple version:\n\n${simplified}\n\n_Note: Connect Groq API key for AI-powered simplification._`,
      });
    }

    let simplified: string;
    try {
      simplified = await groqChat({ apiKey, system: SIMPLIFY_PROMPT, user: answer, temperature: 0.5 });
    } catch (err) {
      if (err instanceof GroqError) {
        console.error("Groq simplify error:", err.status, err.body);
        return NextResponse.json(
          { error: "Could not simplify the answer." },
          { status: 502 }
        );
      }
      throw err;
    }

    return NextResponse.json({ simplified });
  } catch (error) {
    console.error("Simplify API error:", error);
    return NextResponse.json(
      { error: "An unexpected error occurred." },
      { status: 500 }
    );
  }
}
